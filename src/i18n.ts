export const t = (lang: Lang, key: Key) => dict[lang][key];

export const dateFmt = (lang: Lang, iso: string) =>
  new Date(iso).toLocaleDateString(lang === 'de' ? 'de-AT' : 'en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });

export const numFmt = (lang: Lang, n: number) => n.toLocaleString(lang === 'de' ? 'de-AT' : 'en-GB');
